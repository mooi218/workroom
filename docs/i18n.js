// Keep these IDs aligned with lib/roles.mjs. No browser or server dependency is
// needed here, so this module can also be validated directly with Node.
const BUILTIN_ROLE_IDS = new Set([
  "engineering",
  "design",
  "pr",
  "sales",
  "writing",
  "research",
  "planning",
  "operations",
  "other",
]);
const hasOwn = (object, key) =>
  Object.prototype.hasOwnProperty.call(object, key);
let currentLocale = "ja";

export function setLocale(code) {
  const language =
    typeof code === "string"
      ? code.trim().toLowerCase().replaceAll("_", "-").split("-")[0]
      : "";
  currentLocale = hasOwn(TRANSLATIONS, language) ? language : "en";
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function t(key, vars = {}) {
  const name = String(key);
  const local = TRANSLATIONS[currentLocale];
  const template = hasOwn(local, name)
    ? local[name]
    : hasOwn(TRANSLATIONS.en, name)
      ? TRANSLATIONS.en[name]
      : name;
  const values = vars && typeof vars === "object" ? vars : {};
  return template.replace(
    /\{([a-zA-Z][a-zA-Z0-9_]*)\}/g,
    (placeholder, variable) =>
      hasOwn(values, variable) ? String(values[variable] ?? "") : placeholder,
  );
}

export function roleName(role) {
  if (!role || typeof role !== "object") return "";
  if (BUILTIN_ROLE_IDS.has(role.id)) return t(`role.${role.id}`);
  return typeof role.name === "string" ? role.name : "";
}

export function detectLocale(languages = []) {
  for (const item of languages) {
    const code = String(item).toLowerCase().split(/[-_]/)[0];
    if (LANGUAGES.some((language) => language.code === code)) return code;
  }
  return "en";
}
